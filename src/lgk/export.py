"""Export the run as a Databricks Asset Bundle that provisions as a service principal.

The team owns the exported folder in its own git/CI. Synced-table access is tied to the creator,
so the bundle never inherits the workshop's objects: its job runs `provision` as the service
principal (`run_as`), which creates its own synced tables in a new version. Changing the operator
is a new version, not a transfer. The run's workshop state (run.json, manifest) is left out,
so the bundle's provision can neither be skipped as "already succeeded" nor reuse the
workshop's synced tables.

No identity is written into the bundle: the deployer is `${workspace.current_user.userName}`
and the service principal is the bundle variable `sp_app_id`, given at deploy time.
The kit never deploys the bundle itself; it prints the commands.

The service principal builds and owns its own kit tables: the bundle's kit schema is `<kit>_sp`
(or `sp_kit_schema`), never the workshop's, because the nightly build CREATE OR REPLACEs the kit
tables and that needs ownership (MODIFY is not enough). The operator pre-creates the service
principal's schemas and makes the grants; the workshop's kit tables stay the operator's and the
bundle never reads or writes them. A chain with no kit build (an operator SDP pipeline without
`build_mode: sql`, which runs the stamp step) is refused: the SP would label tables nobody
writes into its schema. The workshop's build and enrich records (privacy_bindings.json,
enrich_report.json) do not travel: they name the workshop's tables.

The bundle runs repeatedly: it holds TWO jobs, both run_as the SP and tagged with the graph.
`lgk_provision` runs once per version and refuses a second run: preflight AS THE SP first
(sync_owner_user = the `sp_app_id` variable; CAN_USE on the project is enough, since the bundle
provisions on an existing branch and never creates one), then build -> [enrich] as the SP (so the
tables it serves are its own, built through the same privacy gate and stamp), then provision ->
advise -> switch. `lgk_refresh` is the nightly refresh job that runs the refresh chain:
build -> [enrich] -> sync -> reapply, and never runs provision.
Each task records its own job id in the service principal's run-folder manifest, so teardown deletes the jobs.

Layout written to `<out_dir>`:
    databricks.yml             bundle, variables, permissions, target
    resources/lgk_job.yml      the jobs: lgk_provision (one-time) and lgk_refresh (nightly)
    lgk_task.py                bootstrap: puts the bundled kit code on sys.path, runs one task
    src/lgk/...                the kit code (copy)
    run/...                    the run's config.json, mapping, profile and privacy flags
"""

import json
import re
import shutil
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

import yaml

from lgk import sp_grants
from lgk.refresh.job import refresh_chain, run_enriched
from lgk.runtime import ENVIRONMENT_VERSION  # one pin for every kit job (version 3 = Python 3.12)

# Workshop state that must not travel: re-reading it would skip or reuse the operator's run.
# preflight_result.json names the workshop's sync owner: the SP's own preflight writes the SP's identity.
# privacy_bindings.json and enrich_report.json name the workshop's tables: the SP's own build and
# enrich write the SP's tables, and a travelling copy would be copied over them on every task.
EXCLUDED_RUN_FILES = frozenset({"run.json", "lgk_manifest.json", "versions.json", "branch_manifest.json",
                                "preflight_result.json", "privacy_bindings.json", "enrich_report.json"})
EXCLUDED_RUN_DIRS = frozenset({"bundle", "__pycache__"})
# Config keys that are runtime-only or identities: never written into the bundle.
EXCLUDED_CONFIG_KEYS = frozenset({"run_folder", "workspace_client", "pg_connect", "operator", "user_name",
                                  "sync_owner_user", "sp_kit_schema"})
# Service principal preflight scope: it provisions on an existing branch into a
# version schema the operator made, from Delta tables the operator built.
SP_PREFLIGHT_SCOPE = {"creates_branches": False, "provision_only": True, "sp_builds": True}

SP_VAR = "sp_app_id"
JOB_KEY = "lgk_provision"
REFRESH_JOB_KEY = "lgk_refresh"
NIGHTLY = {"quartz_cron_expression": "0 0 2 * * ?", "timezone_id": "UTC"}
# The bundled code runs from source (sys.path); the job environment installs its dependencies.
DEPENDENCIES = (
    "xxhash>=3.4.1",
    "pydantic>=2.5.0",
    "pydantic-settings>=2.1.0",
    "pyyaml>=6.0",
    "psycopg[binary]>=3.1",
    "databricks-sql-connector>=3.0.0",
    "databricks-sdk>=0.81.0",
)
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")

BOOTSTRAP = '''"""Bundle task bootstrap (generated by lgk.export). Puts the bundled kit code on sys.path."""
import sys

_args = sys.argv[1:]
_src = _args[_args.index("--src") + 1]
sys.path.insert(0, _src if _src.startswith("/Workspace") else "/Workspace" + _src)

from lgk.bundle_entry import main  # noqa: E402

main(_args)
'''


class IdentityInBundleError(RuntimeError):
    """An email address appeared in a generated bundle file."""


MARKER_FILE = ".lgk_bundle"


def export(config: Dict[str, Any], out_dir: Optional[str] = None) -> Path:
    """Write the bundle folder and print the deploy command; returns the folder.

    The bundle is built in a staging folder and moved into place only once it passes the
    identity check, so a refused bundle is never left where it could be deployed.
    """
    run_folder = Path(config["run_folder"])
    out = Path(out_dir) if out_dir else run_folder / "bundle"
    _refuse_unsafe_out_dir(out, run_folder)
    stage = out.with_name(out.name + ".staging")
    shutil.rmtree(stage, ignore_errors=True)
    try:
        _write_bundle(config, run_folder, stage, skip_dirs={out.name, stage.name})
        refuse_identities(stage)
    except Exception:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    if out.exists():
        shutil.rmtree(out)
    stage.rename(out)
    print(deploy_command(out))
    return out


def _refuse_unsafe_out_dir(out: Path, run_folder: Path) -> None:
    """Never delete the run folder (or a parent of it), nor a folder that is not an earlier bundle."""
    o, r = out.resolve(), run_folder.resolve()
    if o == r or o in r.parents:
        raise ValueError(f"export target {out} is the run folder or contains it")
    if o.exists() and not (o / MARKER_FILE).exists():
        raise ValueError(f"export target {out} exists and is not an lgk bundle; refusing to replace it")


def _write_bundle(config: Dict[str, Any], run_folder: Path, out: Path, skip_dirs: set) -> None:
    out.mkdir(parents=True)
    bundle_config = _bundle_config(config)
    enriched = run_enriched(str(run_folder))
    provision_chain(bundle_config, enriched)  # refuses a chain with no kit build, before any file
    _copy_kit_code(out / "src" / "lgk")
    _copy_run_files(run_folder, out / "run", EXCLUDED_RUN_DIRS | skip_dirs)
    (out / "run" / "config.json").write_text(json.dumps(bundle_config, indent=2, sort_keys=True))
    (out / "lgk_task.py").write_text(BOOTSTRAP)
    (out / MARKER_FILE).write_text("generated by lgk.export\n")
    from lgk.mapping import load_mapping

    mapping = load_mapping(run_folder / "graph_mapping.yaml")  # the SP builds from its source schema
    (out / "README.md").write_text(operator_setup(bundle_config, mapping))
    _write_yaml(out / "databricks.yml", databricks_yml(bundle_config))
    _write_yaml(out / "resources" / "lgk_job.yml", job_resource(bundle_config, enriched=enriched))


def sp_kit_schema(config: Dict[str, Any]) -> str:
    """Service principal's kit schema: `sp_kit_schema` when given, else `<kit>_sp`; never the workshop's."""
    from lgk import versions

    workshop = versions.kit_schema(config)
    name = config["sp_kit_schema"] if "sp_kit_schema" in config else sp_grants.default_sp_kit_schema(workshop)
    versions._checked_name(name, "sp_kit_schema")  # a plain identifier, never a version schema name
    if name == workshop:
        raise ValueError(f"sp_kit_schema {name!r} must be the service principal's own kit schema, "
                         f"not the workshop's {workshop!r}")
    return name


def _bundle_config(config: Dict[str, Any]) -> Dict[str, Any]:
    """The run's JSON config for the service principal: identities/runtime keys dropped, bumped version,
    and the SP's own kit schema with the workshop's recorded so every task can refuse it.

    The served schema is pinned to the one the workshop served (its default is the kit schema),
    so the website reads the same schema after the SP's switch.
    """
    from lgk import versions

    kept = {k: v for k, v in config.items() if k not in EXCLUDED_CONFIG_KEYS}
    json.dumps(kept)  # a non-JSON value cannot travel to the job: fail here, not in the workspace
    kept["version"] = int(config.get("version", 1)) + 1
    kept["served_schema"] = versions.served_schema(config)
    kept["workshop_kit_schema"] = versions.kit_schema(config)
    kept["kit_schema"] = sp_kit_schema(config)
    sp_grants.require_own_kit_schema(kept)
    kept.update(SP_PREFLIGHT_SCOPE)
    return kept


def _copy_kit_code(dest: Path) -> None:
    """The kit's own source tree (this package), without bytecode."""
    src = Path(__file__).resolve().parent
    shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def _copy_run_files(run_folder: Path, dest: Path, skip_dirs: frozenset) -> None:
    """The run's inputs (mapping, profile, flags), without the workshop's state."""
    dest.mkdir(parents=True)
    for path in sorted(run_folder.rglob("*")):
        rel = path.relative_to(run_folder)
        if path.is_dir() or rel.parts[0] in skip_dirs or path.name in EXCLUDED_RUN_FILES:
            continue
        if "__pycache__" in rel.parts:
            continue
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)


def bundle_name(config: Dict[str, Any]) -> str:
    return f"lgk_{config['kit_schema']}"


def databricks_yml(config: Dict[str, Any]) -> Dict[str, Any]:
    """Top-level bundle: the SP variable, its CAN_MANAGE (job + files), one default target."""
    return {
        "bundle": {"name": bundle_name(config)},
        "include": ["resources/*.yml"],
        "variables": {
            SP_VAR: {"description": "Application id of the service principal that provisions"},
        },
        "permissions": [{"level": "CAN_MANAGE", "service_principal_name": f"${{var.{SP_VAR}}}"}],
        "targets": {
            "default": {
                "default": True,
                "workspace": {
                    "root_path": ("/Workspace/Users/" +
                                  "${workspace.current_user.userName}" +
                                  "/.bundle/${bundle.name}/${bundle.target}")
                },
            }
        },
    }


def _python_task(key: str, after: Optional[str], extra: Optional[List[str]] = None) -> Dict[str, Any]:
    task: Dict[str, Any] = {
        "task_key": key,
        "environment_key": "lgk",
        "spark_python_task": {
            "python_file": "../lgk_task.py",
            "parameters": [
                "--src", "${workspace.file_path}/src",
                "--run-src", "${workspace.file_path}/run",
                "--run-dir", "${workspace.root_path}/state/run",
                "--task", key,
                "--job-id", "{{job.id}}",  # a job dynamic value: the task records its own job
                *(extra or []),
            ],
        },
    }
    if after:
        task["depends_on"] = [{"task_key": after}]
    return task


def provision_chain(config: Dict[str, Any], enriched: bool) -> List[str]:
    """The provision job's task keys: preflight, the kit build (and enrich) of refresh_chain, provision.

    The service principal builds the tables it serves, through the same tasks as the nightly chain.
    A chain with no kit build (the stamp step) is refused: the SP's kit schema would have no writer.
    """
    chain = refresh_chain(config, enriched)
    if "build" not in chain:
        raise ValueError(
            "the exported bundle's service principal builds its own kit tables, but this run's nightly "
            f"chain {chain} has no kit build (an operator SDP pipeline without build_mode: sql). Set "
            "build_mode: sql in the run config, or keep this graph's refresh on the operator's own job.")
    return ["preflight", *[k for k in chain if k in ("build", "enrich")], "provision"]


def provision_tasks(config: Dict[str, Any], enriched: bool) -> List[Dict[str, Any]]:
    """The one-time provision job: preflight as the SP (the sync owner), build [+ enrich] as the SP, provision."""
    tasks: List[Dict[str, Any]] = []
    for key in provision_chain(config, enriched):
        extra = ["--sync-owner", f"${{var.{SP_VAR}}}"] if key == "preflight" else None
        tasks.append(_python_task(key, tasks[-1]["task_key"] if tasks else None, extra))
    return tasks


def refresh_tasks(config: Dict[str, Any], enriched: bool) -> List[Dict[str, Any]]:
    """The nightly refresh chain tasks, never provision: uses lgk.refresh.job.refresh_chain as bundle tasks.

    The SDP pipeline is a pipeline task; build, stamp, enrich, sync and reapply are python tasks.
    Enrich runs when the run included enrichment (enrich.yaml), so scores recompute instead of going stale.
    """
    tasks: List[Dict[str, Any]] = []
    for key in refresh_chain(config, enriched):
        if key == "sdp_pipeline":
            tasks.append({"task_key": key, "pipeline_task": {"pipeline_id": config["sdp_pipeline_id"]}})
        else:
            tasks.append(_python_task(key, tasks[-1]["task_key"] if tasks else None))
    return tasks


def _job(name: str, config: Dict[str, Any], tasks: List[Dict[str, Any]]) -> Dict[str, Any]:
    from lgk.manifest import job_tags

    return {
        "name": name,
        "max_concurrent_runs": 1,
        "tags": job_tags(config["graph_name"]),
        "run_as": {"service_principal_name": f"${{var.{SP_VAR}}}"},
        "environments": [{
            "environment_key": "lgk",
            "spec": {"environment_version": ENVIRONMENT_VERSION, "dependencies": list(DEPENDENCIES)},
        }],
        "tasks": tasks,
    }


def job_resource(config: Dict[str, Any], enriched: bool = False) -> Dict[str, Any]:
    """The two job resources; run_as is the SP variable, never the deployer."""
    kit = config["kit_schema"]
    refresh = _job(f"lgk_refresh_{kit}", config, refresh_tasks(config, enriched))
    refresh["schedule"] = dict(NIGHTLY)
    return {"resources": {"jobs": {
        JOB_KEY: _job(f"lgk_provision_{kit}", config, provision_tasks(config, enriched)),
        REFRESH_JOB_KEY: refresh,
    }}}


def operator_setup(config: Dict[str, Any], mapping: Any) -> str:
    """The one-time setup the operator does before the SP's first run (no identity written).

    The Unity Catalog statements are lgk.sp_grants.setup_sql: the one list the SP's preflight
    checks and the SKILL shows."""
    from lgk.steps.provision import READER_SETUP_SQL
    from lgk.versions import version_schema

    cat, kit, vs = config["lakebase_catalog"], config["kit_schema"], version_schema(config)
    workshop = config["workshop_kit_schema"]
    sp = sp_grants.SP_PLACEHOLDER
    uc = "\n".join(f"       {line}" for line in sp_grants.setup_sql(
        sp_grants.targets(config, mapping), config["graph_name"], sp))
    return f"""# lgk bundle: build and provision as a service principal

The jobs run as the service principal (`run_as`). It builds its OWN kit tables in `{cat}.{kit}`
(the nightly build replaces them, which needs ownership), from the mapping's source schema
`{mapping.source_catalog}.{mapping.source_schema}`, and creates its own synced tables in
version schema `{vs}`. The workshop's kit tables in {cat}.{workshop} stay the operator's: the
bundle never reads or writes them, and the operator may tear them down.
One-time operator setup, before `databricks bundle deploy`:

1. Unity Catalog (the SP cannot create schemas, so the operator creates both of its schemas;
   the kit never grants anything on a source schema):

{uc}

2. Lakebase project: give the SP `{sp_grants.PROJECT_PERMISSION}` on the project (not CAN_MANAGE: the bundle never
   creates branches; its preflight checks CAN_USE).
3. Postgres, on the branch the bundle targets (or its parent; roles are copied to child branches):

       CREATE EXTENSION IF NOT EXISTS databricks_auth;
       SELECT databricks_create_role('{sp}', 'service_principal');
       {sp_grants.PG_GRANT} TO "{sp}";
       {READER_SETUP_SQL}

   The SP never creates roles: it only grants SELECT on the served views it owns to `reader`,
   and EXECUTE on the served functions it owns to `public_reader` / `coordinator_reader`.

4. The advisor (provision -> advise -> switch) reads the new version's raw tables as the SP:
   it needs USAGE on Postgres schema `{vs}` and SELECT on its tables (the SP creates them, so
   it normally has both). Without them the advisor reports "advisor skipped: <reason>" in
   advisor_report.json and the switch still runs.

The job's first task is `preflight`, as the SP: it records the SP as the sync-job owner, and
provision refuses any other identity. It blocks, listing each missing grant, until 1-3 are done.
Then `build` runs as the SP, through the privacy gate, and stamps its tables; provision refuses
any table not built under the current privacy decision.

Then run the commands `lgk.export` printed, with `LGK_SP_APP_ID` set to the SP's application id.
They deploy both jobs and run `{JOB_KEY}` once. `{REFRESH_JOB_KEY}` then runs nightly (02:00 UTC)
and never re-runs provision; run it by hand with `databricks bundle run {REFRESH_JOB_KEY}`.
"""


def deploy_command(bundle_dir: Path) -> str:
    """The commands the team runs; the SP id comes from their environment, not the bundle."""
    var = f'--var="{SP_VAR}=$LGK_SP_APP_ID"'
    return (
        f"cd {bundle_dir} && databricks bundle deploy {var} && "
        f"databricks bundle run {JOB_KEY} {var}"
    )


def _bundle_files(bundle_dir: Path) -> Iterable[Path]:
    return (p for p in sorted(bundle_dir.rglob("*")) if p.is_file() and p.suffix != ".pyc")


def refuse_identities(bundle_dir: Path) -> None:
    """Raise if any bundle file holds an email address: identities are substituted at deploy time."""
    for path in _bundle_files(bundle_dir):
        rel = str(path.relative_to(bundle_dir))
        found = EMAIL_RE.search(rel) or EMAIL_RE.search(path.read_text(errors="ignore"))
        if found:
            raise IdentityInBundleError(
                f"{rel} contains an email address; the bundle must "
                f"template identities (${{workspace.current_user.userName}}, var.{SP_VAR})"
            )


def _write_yaml(path: Path, data: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(data, sort_keys=False))
